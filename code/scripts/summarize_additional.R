# Summarize already completed blocks; this script never fits models.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2L) stop('Usage: completed-stage-directory summary-directory')
full_args <- commandArgs(FALSE)
script <- sub('^--file=', '', full_args[startsWith(full_args, '--file=')][1])
root <- dirname(dirname(normalizePath(gsub('~+~', ' ', script, fixed = TRUE))))
source(file.path(root, 'R', 'load.R'))
smm <- load_smm(root, compile = FALSE)
files <- list.files(args[1], pattern = '[.]rds$', full.names = TRUE)
if (!length(files)) stop('No completed blocks found.')
results <- lapply(files, readRDS)
stage <- unique(vapply(results, `[[`, '', 'stage'))
stopifnot(length(stage) == 1L)
expected <- unique(smm$additional_plan(stage)[c('scenario', 'replication', 'tpe_seed')])
observed <- bind_rows(lapply(results, '[', names(expected)))
stopifnot(nrow(observed) == nrow(expected), !anyDuplicated(observed),
  setequal(observed, expected))
comparison <- bind_rows(lapply(results, `[[`, 'comparison'))
summary <- smm$summarize_additional(comparison)
dir.create(args[2], recursive = TRUE, showWarnings = FALSE)
write.csv(summary$summary, file.path(args[2], 'paired_effects.csv'), row.names = FALSE)
write.csv(summary$replication_means, file.path(args[2], 'replication_effects.csv'), row.names = FALSE)
