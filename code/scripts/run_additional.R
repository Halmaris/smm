# Explicit single-block runner. Usage is described in docs/SIMULATIONS.md.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 7L || args[1] != '--execute')
  stop('Usage: --execute core|boundary s09|s13|s15 replication seed input-root output-root')
for (name in c('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS'))
  do.call(Sys.setenv, setNames(list('1'), name))
full_args <- commandArgs(FALSE)
script <- sub('^--file=', '', full_args[startsWith(full_args, '--file=')][1])
root <- dirname(dirname(normalizePath(gsub('~+~', ' ', script, fixed = TRUE))))
source(file.path(root, 'R', 'load.R'))
smm <- load_smm(root)
stage <- args[2]; scenario <- args[3]; replication <- as.integer(args[4]); seed <- as.integer(args[5])
block <- sprintf('%s_r%03d', scenario, replication)
input_file <- file.path(args[6], 'blocks', block, 'inputs.rds')
inputs <- readRDS(input_file)
# Pairing is essential here: the boundary experiment must use the same frozen inputs.
attr(inputs, 'identity') <- unname(tools::md5sum(input_file))
name <- sprintf('%s_seed%d.rds', block, seed)
output <- file.path(args[7], stage, name)
if (file.exists(output)) stop('Output already exists; choose an unused output directory.')
core <- if (stage == 'boundary') readRDS(file.path(args[7], 'core', name)) else NULL
result <- smm$run_additional(inputs, scenario, replication, seed, stage, core)
dir.create(dirname(output), recursive = TRUE, showWarnings = FALSE)
saveRDS(result, output)
write.csv(result$comparison, sub('[.]rds$', '.csv', output), row.names = FALSE)
